def _fmt_rub(value: float) -> str:
    return f"{round(value):,}".replace(",", " ") + " ₽"


def _caviar_price_line() -> str:
    known = {k: v for k, v in CAVIAR_PRICES.items() if v}
    if not known:
        return "Цены на текущий период сейчас формируем. Оставь заявку, и Дмитрий пришлет цену, как только она будет утверждена."
    blocks = []
    for kind, price in known.items():
        rows = [f"<b>{kind}</b>"]
        for pack, kg in CAVIAR_PACK_KG.items():
            rows.append(f"▫️ {pack} — <b>{_fmt_rub(price * kg)}</b>")
        blocks.append("\n".join(rows))
    text = "\n\n".join(blocks)
    text += "\n\n▫️ Больше 1 кг — специальная цена, обсудим лично с Дмитрием"
    text += f"\n\n<b>Цена действует до {CAVIAR_PRICE_UNTIL}.</b>"
    text += "\n📈 Подорожание ожидается в начале ноября, следующее в начале декабря."
    return text


